export function formatNegativesForCommander(tokens) {
  return [...new Set(tokens.map((t) => String(t).trim().toLowerCase()).filter(Boolean))]
    .map((t) => (t.startsWith('-') ? t : `-${t}`))
    .join(' ');
}

export function mergeNegatives(...lists) {
  const out = new Set();
  for (const list of lists) {
    for (const item of list || []) {
      const w = String(item).trim().toLowerCase();
      if (w) out.add(w.startsWith('-') ? w.slice(1) : w);
    }
  }
  return [...out];
}

/** Build cross-negative validation records */
export function buildCrossNegativeRecords(groups) {
  const records = [];
  for (const [gid, tokens] of Object.entries(GROUP_CROSS_NEGATIVES_V2)) {
    const g = groups.find((x) => x.id === gid);
    if (!g) continue;
    for (const token of tokens) {
      records.push({
        source_group: gid,
        source_campaign: g.campaign,
        target_competing_intent: token,
        negative_token: token,
        reason: 'sibling_discriminator',
        collision_test: 'pending',
        approved_status: 'approved',
      });
    }
  }
  return records;
}

