-- ---------------------------------------------------------------------------
-- 9) errors
-- ---------------------------------------------------------------------------
CREATE TABLE app_iseo_sales.errors (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  occurred_at timestamptz NOT NULL DEFAULT now(),
  app_component text NULL, -- operational, admin, toolkit
  workflow_version text NULL,
  n8n_execution_id text NULL,
  correlation_id text NULL,
  entity_type text NULL,
  entity_id text NULL,
  error_class text NULL, -- sheets_quota_exceeded, telegram_delivery_failed, …
  provider text NULL,
  code text NULL,
  http_status int NULL,
  stage text NULL,
  retryable boolean NOT NULL DEFAULT false,
  message_sanitized text NULL,
  context jsonb NOT NULL DEFAULT '{}'::jsonb,
  resolved boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT pk_errors PRIMARY KEY (id)
);

-- Soft FK from deliveries.last_error_id
ALTER TABLE app_iseo_sales.deliveries
  ADD CONSTRAINT fk_deliveries_last_error
  FOREIGN KEY (last_error_id) REFERENCES app_iseo_sales.errors (id);

-- ---------------------------------------------------------------------------
-- 10) audit_logs
-- ---------------------------------------------------------------------------
CREATE TABLE app_iseo_sales.audit_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  occurred_at timestamptz NOT NULL DEFAULT now(),
  actor_type text NULL,
  actor_id text NULL,
  action text NOT NULL,
  entity_type text NULL,
  entity_id text NULL,
  correlation_id text NULL,
