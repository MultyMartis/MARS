/**
 * Map release-gate technical pass to allowed next human gates.
 */
export function allowedHumanGatesAfterScriptPass(currentState) {
  const gates = [];
  if (currentState === SEMANTIC_LIFECYCLE_STATES.ARTIFACT_VALIDATED) {
    gates.push(APPROVAL_DISTINCTIONS.CLIENT_APPROVAL);
  }
  if (currentState === SEMANTIC_LIFECYCLE_STATES.CLIENT_APPROVED) {
    gates.push(APPROVAL_DISTINCTIONS.IMPORT_RECONCILIATION);
  }
  if (currentState === SEMANTIC_LIFECYCLE_STATES.IMPORT_RECONCILED) {
    gates.push(APPROVAL_DISTINCTIONS.LAUNCH_APPROVAL);
  }
  return gates;
}
