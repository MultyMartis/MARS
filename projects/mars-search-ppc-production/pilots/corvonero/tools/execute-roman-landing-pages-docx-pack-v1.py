def require_operator_gate() -> None:
    if os.environ.get("CORVONERO_OPERATOR_GATE") != "APPROVED":
        raise SystemExit(
            "STOP: CORVONERO_OPERATOR_GATE=APPROVED required. "
            "This C2b helper is not safe for casual execution."
        )


def main() -> int:
    require_operator_gate()
    if OUT.exists():
        print(f"STOP — OUTPUT DIRECTORY ALREADY EXISTS: {OUT}")
        return 1

    enriched, by_lp, claims = prepare_data()
    if len(enriched) != 71:
        print(f"FAIL — expected 71 groups, got {len(enriched)}")
        return 1

    OUT.mkdir(parents=True)

    generated: list[Path] = []
    for lp_id, fname in LP_FILES.items():
        p = OUT / fname
        write_docx(lp_id, by_lp[lp_id], p)
        generated.append(p)
        print(f"Wrote {p.name}")

    map_xlsx = OUT / "CORVONERO-CAMPAIGN-GROUP-TO-LANDING-MAP-v1.xlsx"
    write_mapping_xlsx(enriched, map_xlsx)
    generated.append(map_xlsx)

    conf_xlsx = OUT / "CORVONERO-LANDING-PAGES-OPEN-CONFIRMATIONS-v1.xlsx"
    write_confirmations_xlsx(claims, conf_xlsx)
    generated.append(conf_xlsx)

    readme = OUT / "README-CORVONERO-ROMAN-LANDING-PAGES-PACK-v1.md"
    write_readme(readme)
    generated.append(readme)

    manifest = OUT / "CORVONERO-ROMAN-LANDING-PAGES-PACK-MANIFEST-v1.json"
    write_manifest(generated, manifest)
    generated.append(manifest)

    checksums = OUT / "CORVONERO-ROMAN-LANDING-PAGES-PACK-SHA256SUMS-v1.txt"
    write_checksums([f for f in generated if f != checksums and f != manifest], checksums)
    generated.append(checksums)

    # refresh manifest with all files
    write_manifest(generated, manifest)

    write_repo_refs(enriched, claims)
    write_report(enriched, claims, generated)

    print("PASS — pack complete")
    return 0


if __name__ == "__main__":
    sys.exit(main())
