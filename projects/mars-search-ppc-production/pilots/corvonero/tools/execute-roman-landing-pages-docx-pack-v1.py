def prepare_data() -> tuple[list[dict], dict, list[dict]]:
    groups_raw = load_json(PILOTS / "CORVONERO-CAMPAIGN-V2.6-FINAL-GROUP-PLAN-v1.json")["groups"]
    ads_raw = load_json(PILOTS / "CORVONERO-CAMPAIGN-V2.6-FINAL-AD-COPY-v1.json")["ads"]
    claims = load_json(PILOTS / "client-approval/CORVONERO-CLIENT-COMMERCIAL-CLAIMS-REGISTER-v1.json")["claims"]

    ad_lookup = {(a["campaign"], a["group_id"]): a for a in ads_raw}

    enriched = []
    for g in groups_raw:
        ad = ad_lookup.get((g["campaign"], g["group_id"]), {})
        lp = URL_TO_LP[g["landing_url"]]
        service = lp.replace("LP-0", "CA-0")[:5] if lp.startswith("LP-0") else ""
        service_map = {"LP-01": "CA-01", "LP-02": "CA-02", "LP-03": "CA-03", "LP-04": "CA-04", "LP-05": "CA-05"}
        enriched.append({
            **g,
            "landing_page": lp,
            "service": service_map[lp],
            "headline_1": ad.get("headline_1", ""),
            "headline_2": ad.get("headline_2", ""),
            "group_intent": g["group_name"],
            "section": GROUP_SECTION.get(g["group_id"], "§6 Page structure"),
        })

    by_lp: dict[str, list[dict]] = {k: [] for k in LP_URLS}
    for row in enriched:
        by_lp[row["landing_page"]].append(row)

    return enriched, by_lp, claims


