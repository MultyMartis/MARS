def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def add_page_number(section) -> None:
    footer = section.footer
    p = footer.paragraphs[0] if footer.paragraphs else footer.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run()
    for el in (
        ("begin", None),
        ("preserve", "PAGE"),
        ("separate", None),
        ("end", None),
    ):
        if el[0] == "preserve":
            instr = OxmlElement("w:instrText")
            instr.set(qn("xml:space"), "preserve")
            instr.text = el[1]
            run._r.append(instr)
        else:
            fld = OxmlElement("w:fldChar")
            fld.set(qn("w:fldCharType"), el[0])
            run._r.append(fld)


def new_doc(page: dict) -> Document:
    doc = Document()
    sec = doc.sections[0]
    sec.page_height = Cm(29.7)
    sec.page_width = Cm(21.0)
    sec.top_margin = Cm(2.0)
    sec.bottom_margin = Cm(2.0)
    sec.left_margin = Cm(2.5)
    sec.right_margin = Cm(2.0)

    style = doc.styles["Normal"]
    style.font.name = "Calibri"
    style.font.size = Pt(11)

    header = sec.header
    hp = header.paragraphs[0] if header.paragraphs else header.add_paragraph()
    hp.text = f"Корво Неро · {page['page_name']} · {page['url']}"
    hp.alignment = WD_ALIGN_PARAGRAPH.RIGHT

    footer = sec.footer
    fp = footer.paragraphs[0] if footer.paragraphs else footer.add_paragraph()
    fp.clear()
    fp.add_run(FOOTER_TEXT + " · ")
    add_page_number(sec)

    title = doc.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r1 = title.add_run("Корво Неро")
    r1.bold = True
    r1.font.size = Pt(14)
    r2 = title.add_run(f"\n{page['page_name']}")
    r2.bold = True
    r2.font.size = Pt(12)
    doc.add_paragraph(page["url"]).alignment = WD_ALIGN_PARAGRAPH.CENTER
    doc.add_paragraph()
    return doc


def add_bullets(doc: Document, items: list[str]) -> None:
    for item in items:
        doc.add_paragraph(item, style="List Bullet")


def add_scenario_cards(doc: Document, scenarios: list[tuple[str, str]]) -> None:
    for title, body in scenarios:
        p = doc.add_paragraph()
        r = p.add_run(title)
        r.bold = True
        doc.add_paragraph(body)


def add_faq(doc: Document, items: list[tuple[str, str]]) -> None:
    for q, a in items:
        p = doc.add_paragraph()
        rq = p.add_run(q)
        rq.bold = True
        doc.add_paragraph(a)
        doc.add_paragraph()


